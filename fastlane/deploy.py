"""Put your dashboard on Vercel: a password-protected, read-only copy on your own Vercel account.

    vercel login                                  # once (Vercel CLI: npm i -g vercel)
    python3 -m fastlane.deploy                    # build a snapshot of your ledger and deploy it
    python3 -m fastlane.deploy --watch 30         # keep it in sync: redeploy every 30 min when the ledger changed
    python3 -m fastlane.run --vercel              # run the engine and keep the Vercel copy in sync alongside it
    python3 -m fastlane.deploy --dry-run          # build the bundle only (fastlane/results/vercel/<project>)

The engine keeps running on your machine (Vercel cannot hold the news pollers or the Kalshi WebSocket). What goes
to Vercel is a snapshot of your ledger, the dashboard, and a salted hash of the password. The first deploy prints
the password once and stores it in fastlane/results/vercel.json (gitignored, readable only by you). The real-money
switch never works on the Vercel copy.

Vercel's free plan allows 100 deployments a day, so --watch refuses intervals under 20 minutes.
"""
import argparse
import hashlib
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path
from urllib.parse import quote

from fastlane import backup, errors
from fastlane.config import RESULTS_DIR, ROOT, kalshi_is_demo, load_env
from fastlane.ledger import DB_PATH
from fastlane.universe import CACHE

STATE_FILE = RESULTS_DIR / "vercel.json"
BUILD_ROOT = RESULTS_DIR / "vercel"
PKG = ROOT / "fastlane"
MIN_WATCH_MINUTES = 20
PROJECT_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,98}[a-z0-9]$")

VERCEL_JSON = {
    # Static output comes ONLY from the empty public/ folder. Without this, Vercel would serve files in the project
    # root (the ledger, the password hash) directly, before the rewrite and the password check.
    "outputDirectory": "public",
    "rewrites": [{"source": "/(.*)", "destination": "/api/index"}],
    "functions": {"api/index.py": {"includeFiles": "fastlane/**", "maxDuration": 10}},
    "headers": [{"source": "/(.*)", "headers": [
        {"key": "X-Robots-Tag", "value": "noindex"}, {"key": "X-Content-Type-Options", "value": "nosniff"},
        {"key": "Referrer-Policy", "value": "no-referrer"}, {"key": "X-Frame-Options", "value": "DENY"}]}],
}
ENTRYPOINT = '"""Vercel entry point, generated by python3 -m fastlane.deploy."""\nfrom fastlane.hosted import app  # noqa: F401\n'


class DeployError(RuntimeError):
    pass


DEMO_REFUSAL = "refusing to publish: KALSHI_BASE_URL is the demo host, the hosted copy would show demo data as yours"


def refuse_if_demo():
    try:
        demo = kalshi_is_demo()
    except ValueError:
        demo = False
    if demo:
        raise DeployError(DEMO_REFUSAL)


def load_state() -> dict:
    try:
        return json.loads(STATE_FILE.read_text())
    except (OSError, ValueError):
        return {}


def save_state(state: dict):
    STATE_FILE.parent.mkdir(exist_ok=True)
    fd = os.open(STATE_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(state, f, indent=1)
    os.chmod(STATE_FILE, 0o600)   # O_CREAT's mode only applies to a new file


def _trim_universe(market_ids: set[str], out: Path):
    """Only the markets that appear in the ledger (Polymarket token ids are needed for live prices)."""
    try:
        markets = json.loads(CACHE.read_text()) if CACHE.exists() else []
    except (OSError, ValueError):
        markets = []
    out.write_text(json.dumps([m for m in markets if m.get("id") in market_ids]))


def _market_ids(db_path: Path) -> set[str]:
    import sqlite3
    db = sqlite3.connect(f"file:{quote(str(db_path))}?mode=ro", uri=True)
    try:
        return {r[0] for r in db.execute("SELECT market_id FROM trades UNION SELECT market_id FROM decisions")
                if r[0]}
    finally:
        db.close()


def _requirements() -> str:
    """The repo's runtime requirements (no test tools)."""
    lines = [l.strip() for l in (ROOT / "requirements.txt").read_text().splitlines()]
    return "\n".join(l for l in lines if l and not l.startswith(("#", "pytest"))) + "\n"


def build(project: str, password_hash: dict, src_db: Path = DB_PATH, out_root: Path = BUILD_ROOT) -> Path:
    """Assemble the deployable folder. Keeps .vercel/ (the project link) between builds."""
    out = out_root / project
    out.mkdir(parents=True, exist_ok=True)
    for child in out.iterdir():
        if child.name != ".vercel":
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    pkg = out / "fastlane"
    # Code and the dashboard only: a stray .env, .pem or .key a user dropped into fastlane/ never ships.
    pkg.mkdir()
    for f in PKG.glob("*.py"):
        shutil.copy2(f, pkg / f.name)
    shutil.copytree(PKG / "static", pkg / "static", ignore=shutil.ignore_patterns(".*"))
    results = pkg / "results"
    results.mkdir()
    if src_db.exists():
        counts = backup.snapshot(results / "ledger.db", src_db)
        _trim_universe(_market_ids(results / "ledger.db"), results / "universe.json")
    else:
        counts = {}
    (pkg / "hosted_auth.json").write_text(json.dumps(password_hash))
    (pkg / "hosted_meta.json").write_text(json.dumps({"snapshot_ts": time.time(), "counts": counts,
                                                      "telemetry_dsn": errors.telemetry_dsn()}))
    (out / "public").mkdir()
    (out / "public" / "robots.txt").write_text("User-agent: *\nDisallow: /\n")
    (out / "api").mkdir()
    (out / "api" / "index.py").write_text(ENTRYPOINT)
    (out / "requirements.txt").write_text(_requirements())
    (out / "vercel.json").write_text(json.dumps(VERCEL_JSON, indent=1))
    (out / ".vercelignore").write_text("__pycache__\n*.pyc\n")
    return out


def ledger_fingerprint(db_path: Path = DB_PATH) -> str:
    """Changes whenever the ledger gains rows; cheap enough to check every few minutes."""
    import sqlite3
    if not db_path.exists():
        return ""
    db = sqlite3.connect(f"file:{quote(str(db_path))}?mode=ro", uri=True)
    try:
        counts = backup.table_counts(db)
        latest = db.execute("SELECT MAX(ts) FROM marks").fetchone()[0] if "marks" in counts else None
    finally:
        db.close()
    return hashlib.sha256(json.dumps([counts, latest], sort_keys=True).encode()).hexdigest()[:16]


def _vercel_cmd() -> list[str]:
    if shutil.which("vercel"):
        return ["vercel"]
    if shutil.which("npx"):
        return ["npx", "--yes", "vercel@latest"]
    raise DeployError("Vercel CLI not found. Install it with: npm i -g vercel")


def _run(args: list[str], cwd: Path, check: bool = True, input_text: str | None = None) -> subprocess.CompletedProcess:
    p = subprocess.run(_vercel_cmd() + args, cwd=cwd, capture_output=True, text=True, input=input_text, timeout=600)
    if check and p.returncode != 0:
        raise DeployError(f"vercel {' '.join(args[:2])} failed: {errors.scrub((p.stderr or p.stdout)[-600:], 600)}")
    return p


def ensure_login(cwd: Path) -> str:
    p = _run(["whoami"], cwd, check=False)
    if p.returncode != 0:
        raise DeployError("not logged in to Vercel. Run `vercel login` once, then try again.")
    return p.stdout.strip().splitlines()[-1] if p.stdout.strip() else "?"


def deploy(project: str, out: Path) -> str:
    """Link (creating the project the first time) and deploy to production. Returns the deployment URL."""
    if not (out / ".vercel" / "project.json").exists():
        _run(["project", "add", project], out, check=False)  # fails harmlessly when it already exists
        _run(["link", "--yes", "--project", project], out)
    p = _run(["deploy", "--prod", "--yes"], out)
    urls = re.findall(r"https://[a-z0-9.-]+\.vercel\.app", p.stdout + p.stderr)
    if not urls:
        raise DeployError("deploy finished but no URL was printed; check `vercel ls`")
    return urls[-1]


def setup(name: str | None, password: str | None) -> tuple[dict, str | None]:
    """First run: pick a project name and password. Returns (state, password shown once or None)."""
    refuse_if_demo()
    state = load_state()
    shown = None
    if name:
        if not PROJECT_RE.match(name):
            raise DeployError("project name: lowercase letters, digits and dashes, 2 to 100 characters")
        state["project"] = name
    state.setdefault("project", f"fastlane-dashboard-{secrets.token_hex(3)}")
    if password is not None and len(password) < 12:
        raise DeployError("--password must be at least 12 characters (the URL is public; only the password guards it)")
    if password or "password_hash" not in state:
        from fastlane.passwords import hash_password
        shown = password or secrets.token_urlsafe(12)
        state["password_hash"] = hash_password(shown)
        if not password:
            state["password"] = shown  # generated: kept so the user can look it up again (file is 0600)
        else:
            state.pop("password", None)
    save_state(state)
    return state, shown


def sync(force: bool = False, dry_run: bool = False) -> str | None:
    """Build and deploy if the ledger changed since the last deploy. Returns the URL, or None when skipped."""
    refuse_if_demo()
    state = load_state()
    if "project" not in state:
        raise DeployError("run python3 -m fastlane.deploy once first")
    fp = ledger_fingerprint()
    if not force and fp and fp == state.get("fingerprint"):
        return None
    out = build(state["project"], state["password_hash"])
    if dry_run:
        return str(out)
    ensure_login(out)
    url = deploy(state["project"], out)
    state.update(fingerprint=fp, url=url, deployed_ts=time.time())
    save_state(state)
    return url


def watch(minutes: float, stop: threading.Event | None = None, quiet: bool = False):
    """Redeploy every `minutes` when the ledger changed. Errors are reported and the loop keeps going."""
    minutes = max(minutes, MIN_WATCH_MINUTES)
    stop = stop or threading.Event()
    while not stop.is_set():
        try:
            url = sync()
            if url and not quiet:
                print(f"vercel: dashboard synced -> {url}")
        except DeployError as exc:
            print(f"vercel: {exc}")
            errors.message(str(exc)[:200], "deploy.sync")
        except Exception as exc:
            errors.capture(exc, "deploy.sync")
        stop.wait(minutes * 60)


def start_background(minutes: float) -> threading.Event:
    """Used by `fastlane.run --vercel`."""
    stop = threading.Event()
    threading.Thread(target=watch, args=(minutes, stop, False), name="vercel-sync", daemon=True).start()
    return stop


def main(argv=None) -> int:
    load_env()
    errors.init("deploy")
    ap = argparse.ArgumentParser(description="Deploy a password-protected, read-only copy of your dashboard to Vercel.")
    ap.add_argument("--name", help="Vercel project name (default: fastlane-dashboard-<random>)")
    ap.add_argument("--password", help="dashboard password (default: generated and printed once)")
    ap.add_argument("--watch", type=float, metavar="MINUTES", help=f"keep syncing (minimum {MIN_WATCH_MINUTES})")
    ap.add_argument("--dry-run", action="store_true", help="build the bundle only, do not deploy")
    a = ap.parse_args(argv)
    try:
        state, shown = setup(a.name, a.password)
        if a.watch:
            print(f"vercel: syncing {state['project']} every {max(a.watch, MIN_WATCH_MINUTES):.0f} min (Ctrl-C to stop)")
            watch(a.watch)
            return 0
        url = sync(force=True, dry_run=a.dry_run)
    except DeployError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130
    if a.dry_run:
        print(f"bundle built: {url}")
        return 0
    print(f"dashboard: {url}")
    if shown:
        print(f"password:  {shown}   (any username; stored in {STATE_FILE.relative_to(ROOT)})")
    print("keep it in sync: python3 -m fastlane.deploy --watch 30   or   python3 -m fastlane.run --vercel")
    return 0


if __name__ == "__main__":
    sys.exit(main())
